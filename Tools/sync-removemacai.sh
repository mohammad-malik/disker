#!/bin/bash
# Refreshes the vendored copy of RemoveMacAI (github.com/omlahore/RemoveMacAI).
#
#   Tools/sync-removemacai.sh            # newest release, prereleases included
#   Tools/sync-removemacai.sh v1.1.4     # a tag, branch or commit
#
# Upstream ships a release every few days, and the fixes are in exactly the parts that rot:
# asset-set names, settings keys, Music's launch label, which macOS has which feature. So the
# copy is never edited by hand. `Sources/RemoveMacAIKit/Upstream` and `Sources/UAF` mirror
# upstream byte for byte, and everything Disker needs lives in `DebloatBridge.swift` beside
# them, which this script leaves alone (it also regenerates `UpstreamRelease.swift`, the
# record of which release is inside). Resyncing is then this script plus a build.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"

REPO="omlahore/RemoveMacAI"
REF="${1:-}"
if [[ -z "$REF" ]]; then
    REF="$(gh api "repos/$REPO/releases?per_page=1" --jq '.[0].tag_name')"
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
git clone --quiet "https://github.com/$REPO.git" "$WORK/src"
git -C "$WORK/src" -c advice.detachedHead=false checkout --quiet "$REF"
COMMIT="$(git -C "$WORK/src" rev-parse HEAD)"
# The upstream commit's own date, not today's: what the Debloat window shows is how old the
# copy is, and a sync that changes nothing must not make it look fresher.
DATE="$(git -C "$WORK/src" log -1 --format=%cs)"

KIT="$REPO_ROOT/Sources/RemoveMacAIKit"
rm -rf "$KIT/Upstream" "$REPO_ROOT/Sources/UAF"
cp -R "$WORK/src/Sources/removemacai" "$KIT/Upstream"
cp -R "$WORK/src/Sources/UAF" "$REPO_ROOT/Sources/UAF"
cp "$WORK/src/LICENSE" "$KIT/Upstream/LICENSE"
cp "$WORK/src/THIRD-PARTY-NOTICES.md" "$KIT/Upstream/THIRD-PARTY-NOTICES.md"

cat > "$KIT/Upstream/UPSTREAM" <<EOF
repository: https://github.com/$REPO
ref: $REF
commit: $COMMIT
EOF

# Generated alongside the bridge rather than read from UPSTREAM at run time, so the app has
# no resource to bundle and the build fails loudly if the file goes missing.
cat > "$KIT/UpstreamRelease.swift" <<EOF
// Generated by Tools/sync-removemacai.sh. Do not edit.

extension Debloat {
    /// The upstream tag, branch or commit that was vendored.
    public static let upstreamRef = "$REF"
    public static let upstreamCommit = "$COMMIT"
    /// The upstream commit's date, YYYY-MM-DD.
    public static let upstreamDate = "$DATE"
}
EOF

echo "RemoveMacAI $REF ($COMMIT) vendored. Build with Tools/build.sh to check the bridge still fits."
